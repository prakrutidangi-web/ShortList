"""Check candidate boards against the live APIs; keep ONLY those that return HTTP 200 with jobs."""

import json
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

import yaml

from shortlist_ml.ingest.companies import CompanyConfig, parse_companies
from shortlist_ml.ingest.http import Fetcher
from shortlist_ml.ingest.sources import SOURCES, greenhouse_url, lever_url


@dataclass(frozen=True)
class Verification:
    company: CompanyConfig
    ok: bool
    jobs: int
    detail: str


def verify_one(cfg: CompanyConfig, fetcher: Fetcher) -> Verification:
    # content=false keeps verification light; the job list is the same.
    url = (
        greenhouse_url(cfg.board_token, content=False)
        if cfg.ats == "greenhouse"
        else lever_url(cfg.board_token)
    )
    res = fetcher.get(url)
    if res.status_code != 200:
        return Verification(cfg, False, 0, res.error or f"HTTP {res.status_code}")
    try:
        data = json.loads(res.content)
    except ValueError:
        return Verification(cfg, False, 0, "HTTP 200 but not JSON")
    jobs = data.get("jobs") if isinstance(data, dict) else data
    if not isinstance(jobs, list):
        return Verification(cfg, False, 0, "HTTP 200 but unexpected JSON shape")
    if not jobs:
        return Verification(cfg, False, 0, "HTTP 200 but zero jobs")
    return Verification(cfg, True, len(jobs), "ok")


def verify_all(
    candidates_file: Path, out_file: Path, report_file: Path, fetcher: Fetcher
) -> list[Verification]:
    rows = yaml.safe_load(candidates_file.read_text()) or []
    # Entries whose ATS we don't support (own careers site, Ashby, ...) are reported, never fetched.
    supported = [r for r in rows if str(r.get("ats")) in SOURCES]
    skipped = [r for r in rows if str(r.get("ats")) not in SOURCES]
    results = [verify_one(cfg, fetcher) for cfg in parse_companies(supported, candidates_file)]
    good = [r for r in results if r.ok]
    out_file.write_text(
        "# Generated by `make verify-companies`. Only boards that returned HTTP 200 with jobs.\n"
        + yaml.safe_dump(
            [
                {"name": r.company.name, "ats": r.company.ats, "board_token": r.company.board_token}
                for r in good
            ],
            sort_keys=False,
        )
    )
    lines = [
        "# Company verification report",
        "",
        f"Generated {datetime.now(UTC):%Y-%m-%d %H:%M} UTC by `make verify-companies`. "
        f"{len(good)} of {len(results)} candidates verified.",
        "",
        "| Company | ATS | Board token | Result | Jobs |",
        "|---|---|---|---|---|",
    ]
    for r in sorted(results, key=lambda r: (not r.ok, r.company.name.lower())):
        c = r.company
        lines.append(
            f"| {c.name} | {c.ats} | `{c.board_token}` | {'OK' if r.ok else 'FAILED: ' + r.detail} | {r.jobs or ''} |"
        )
    if skipped:
        lines += [
            "",
            "## Not attempted (not on Greenhouse/Lever; Shortlist does not scrape other sites)",
            "",
            "| Company | Believed to use | Note |",
            "|---|---|---|",
        ]
        lines += [f"| {r.get('name')} | {r.get('ats')} | {r.get('note', '')} |" for r in skipped]
    report_file.write_text("\n".join(lines) + "\n")
    return results
